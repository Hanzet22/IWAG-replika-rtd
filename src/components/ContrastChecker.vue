<script setup lang="ts">
import { ref } from "vue";

const props = defineProps<{ lang: string }>();
const isId = props.lang === "id";
const foreground = ref("#14232e");
const background = ref("#f4f6f7");
const ratio = ref<number | null>(null);
const engine = ref("");
const message = ref(isId
  ? "Pilih dua warna lalu hitung rasio kontras."
  : "Choose two colours, then calculate their contrast ratio.");

function rgb(hex: string): [number, number, number] {
  const value = hex.replace("#", "");
  return [
    Number.parseInt(value.slice(0, 2), 16),
    Number.parseInt(value.slice(2, 4), 16),
    Number.parseInt(value.slice(4, 6), 16)
  ];
}

function linear(channel: number): number {
  const value = channel / 255;
  return value <= 0.04045 ? value / 12.92 : Math.pow((value + 0.055) / 1.055, 2.4);
}

function jsContrast(first: [number, number, number], second: [number, number, number]): number {
  const luminance = (color: [number, number, number]) =>
    0.2126 * linear(color[0]) + 0.7152 * linear(color[1]) + 0.0722 * linear(color[2]);
  const a = luminance(first);
  const b = luminance(second);
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}

async function calculate() {
  const first = rgb(foreground.value);
  const second = rgb(background.value);
  let result: number;
  try {
    // Generated by the optional Rust/WASM build command.
    // @ts-ignore - generated into public/wasm during the CI build.
    const wasm = await import(/* @vite-ignore */ "/wasm/iwag_contrast_engine.js");
    await wasm.default();
    result = wasm.contrast_ratio(...first, ...second);
    engine.value = "Rust/WASM";
  } catch {
    result = jsContrast(first, second);
    engine.value = "JavaScript fallback";
  }
  ratio.value = result;
  const formatted = result.toFixed(2) + ":1";
  if (result >= 4.5) {
    message.value = isId
      ? formatted + " — memenuhi ambang 4,5:1 untuk teks normal dan 3:1 untuk teks besar."
      : formatted + " — meets the 4.5:1 normal-text and 3:1 large-text thresholds.";
  } else if (result >= 3) {
    message.value = isId
      ? formatted + " — memenuhi ambang 3:1 untuk teks besar, belum 4,5:1 untuk teks normal."
      : formatted + " — meets the 3:1 large-text threshold, but not 4.5:1 for normal text.";
  } else {
    message.value = isId
      ? formatted + " — di bawah ambang 3:1 untuk teks besar."
      : formatted + " — below the 3:1 large-text threshold.";
  }
}
</script>

<template>
  <section class="content-card contrast-checker" aria-labelledby="contrast-checker-title">
    <p class="eyebrow">OPTIONAL RUST / WASM UTILITY</p>
    <h2 id="contrast-checker-title">{{ isId ? "Pemeriksa kontras warna" : "Colour contrast checker" }}</h2>
    <p>{{ isId ? "Hitung rasio kontras dua warna sRGB. Jika modul Rust/WASM tersedia, pemeriksaan memakainya; jika tidak, perhitungan JavaScript lokal menjadi fallback." : "Calculate the contrast ratio between two sRGB colours. When the Rust/WASM module is available it is used; otherwise a local JavaScript calculation is the fallback." }}</p>
    <div class="contrast-inputs">
      <div>
        <label for="contrast-foreground">{{ isId ? "Warna teks" : "Text colour" }}</label>
        <input id="contrast-foreground" v-model="foreground" type="color" />
        <code>{{ foreground.toUpperCase() }}</code>
      </div>
      <div>
        <label for="contrast-background">{{ isId ? "Warna latar" : "Background colour" }}</label>
        <input id="contrast-background" v-model="background" type="color" />
        <code>{{ background.toUpperCase() }}</code>
      </div>
    </div>
    <div class="contrast-preview" :style="{ color: foreground, backgroundColor: background }">
      <strong>{{ isId ? "Contoh teks" : "Sample text" }}</strong>
      <span>{{ isId ? "Pratinjau kombinasi warna" : "Preview of this colour pairing" }}</span>
    </div>
    <button type="button" class="action-link" @click="calculate">
      {{ isId ? "Hitung rasio kontras" : "Calculate contrast ratio" }}
    </button>
    <p class="contrast-result" role="status" aria-live="polite">{{ message }}</p>
    <p v-if="ratio !== null" class="muted">{{ isId ? "Mesin:" : "Engine:" }} {{ engine }}</p>
    <p class="muted">{{ isId ? "Pemeriksaan ini hanya menghitung dua warna sRGB opak. Ini bukan audit WCAG atau sertifikasi; ukuran teks, font, transparansi, gambar, dan konteks antarmuka tetap perlu diperiksa." : "This checks only two opaque sRGB colours. It is not a WCAG audit or certification; text size, typeface, transparency, images and interface context still need review." }}</p>
  </section>
</template>
